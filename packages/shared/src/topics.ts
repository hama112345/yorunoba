/** 1日に掲示板に出すお題の数 */
export const TOPICS_PER_DAY = 3;

const JST_OFFSET_MS = 9 * 60 * 60 * 1000;
/** 店の「1日」は日本時間の朝5時で切り替える（深夜0時をまたいでも同じ夜のお題にする） */
const DAY_START_HOUR = 5;

/** その日（日本時間）の通し番号 */
function dayNumber(now: number) {
  return Math.floor((now + JST_OFFSET_MS - DAY_START_HOUR * 60 * 60 * 1000) / 86_400_000);
}

/**
 * 今日のお題（日付で決まるので、誰が見ても同じ。日ごとに順番にずれていく）。
 * TOPICS_PER_DAY 個を、重ならないように返す
 */
export function todaysTopics(now = Date.now()): string[] {
  const start = (dayNumber(now) * TOPICS_PER_DAY) % TOPICS.length;
  return Array.from({ length: TOPICS_PER_DAY }, (_, i) => TOPICS[(start + i) % TOPICS.length]);
}
